"""miniagent —— 手写终端编码智能体。

设计原则（这三条决定了整个项目的形状，也是面试要讲的东西）:

1. **不依赖任何 Agent 编排框架**（LangChain / LangGraph / CrewAI 都不用）。
   理由: 本项目要练的正是 loop 本身。编排框架会替你写掉
   "请求 -> 工具分发 -> 结果回填 -> 再请求" 这段，而那正是 Agent 工程的核心。

2. **context/ 层不调用 LLM**。
   理由: 上下文处理如果嵌了模型调用，压缩就会递归地消耗上下文 ——
   你为了省 token 去调一次模型，这次调用自己又要占 token。
   所以除了"生成摘要"这一个明确的例外，context/ 里全是纯函数。

3. **工具输出一律先过上下文层，再进消息历史**。
   理由: 单次 read_file 就能返回几十万 token。若原样回填，
   下一轮请求必然超限。截断必须发生在"进入历史"这个入口，而不是等报错再补救。
"""

